#define GGML_RESTRICT restrict
#define QK_K 256
#define MAX(a,b) ((a)>(b)?(a):(b))
#define MIN(a,b) ((a)<(b)?(a):(b))
#define GGML_FP32_TO_FP16(x) ((_Float16)(x))
#define GGML_FP16_TO_FP32(x) ((float)(x))
typedef struct {uint8_t scales[16],qs[64];_Float16 d,dmin;} block_q2_K;
_Static_assert(sizeof(block_q2_K)==84,"Q2_K layout differs");
